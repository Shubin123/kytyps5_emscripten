#!/usr/bin/env python3
"""Regenerate src/web/hle_names.inc from tools/web/hle_names.txt.

PS4/PS5 binaries import symbols by NID: the first 8 bytes of
SHA-1(name + fixed suffix), byte-reversed, base64-encoded with '-' for '/'.
"""
import base64
import hashlib
import pathlib
import struct

SUFFIX = bytes.fromhex('518D64A635DED8C1E6B039B1C3E55230')
ROOT = pathlib.Path(__file__).resolve().parents[2]


def nid(name):
    digest = hashlib.sha1(name.encode() + SUFFIX).digest()[:8]
    raw = struct.pack('<Q', struct.unpack('>Q', digest)[0])
    return base64.b64encode(raw).decode().rstrip('=').replace('/', '-')


names = sorted(set((ROOT / 'tools/web/hle_names.txt').read_text().split()))
lines = [f'{{"{nid(n)}", "{n}"}},' for n in names]
(ROOT / 'src/web/hle_names.inc').write_text(
    '// Generated by tools/web/gen_hle_names.py; do not edit.\n' + '\n'.join(lines) + '\n')
print(f'wrote {len(names)} names')
